#!/usr/bin/env python3
"""Draw the figures from the CSVs the other scripts wrote.

Deliberately the only file in this repo that imports matplotlib, which is not installed
on the machine this was developed on. Every number the figures show is already in
results/*.csv and every one of those CSVs is produced by `make results` with numpy
alone, so a reader without matplotlib reproduces the whole project and simply does not
get pictures.

    python3 -m venv .venv && .venv/bin/pip install matplotlib
    .venv/bin/python analysis/plot_results.py
"""

from __future__ import annotations

import csv
import pathlib
import sys

RESULTS = pathlib.Path(__file__).resolve().parents[1] / "results"

try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    sys.exit("matplotlib is not installed, and it is intentionally not required to "
             "reproduce any result in this repo -- see results/*.csv, which are "
             "committed and regenerated by `make results`.\n"
             "  python3 -m venv .venv && .venv/bin/pip install matplotlib\n"
             "  .venv/bin/python analysis/plot_results.py")


def read(name: str) -> list[dict]:
    path = RESULTS / name
    if not path.exists():
        sys.exit(f"{path} missing -- run `make results` first.")
    with path.open() as fh:
        return list(csv.DictReader(fh))


def plot_divergence() -> None:
    """The picture the project exists for: naive going indefinite, Joseph not."""
    rows = read("divergence_trace.csv")
    t = [float(r["t"]) for r in rows]
    fig, ax = plt.subplots(3, 1, figsize=(8, 9), sharex=True)

    ax[0].axhline(0.0, color="0.5", lw=0.8)
    ax[0].plot(t, [float(r["naive_lambda_min"]) for r in rows], label="naive")
    ax[0].plot(t, [float(r["joseph_lambda_min"]) for r in rows], label="Joseph")
    ax[0].set_ylabel(r"$\lambda_{\min}(P)$  [rad$^2$]")
    ax[0].set_title("Fixed-point covariance, Kalman gain in Q1.12")
    ax[0].legend()

    ax[1].semilogy(t, [max(float(r["naive_sym_resid"]), 1e-18) for r in rows],
                   label="naive")
    ax[1].semilogy(t, [max(float(r["joseph_sym_resid"]), 1e-18) for r in rows],
                   label="Joseph (identically zero)")
    ax[1].set_ylabel(r"$\|P-P^{\mathsf T}\|$")
    ax[1].legend()

    ax[2].plot(t, [float(r["naive_angle_err_deg"]) for r in rows], label="naive")
    ax[2].plot(t, [float(r["joseph_angle_err_deg"]) for r in rows], label="Joseph")
    ax[2].set_ylabel("angle $-$ float64  [deg]")
    ax[2].set_xlabel("t [s]")
    ax[2].legend()
    fig.tight_layout()
    fig.savefig(RESULTS / "divergence.png", dpi=140)
    plt.close(fig)


def plot_predicted_vs_measured() -> None:
    rows = read("gain_bits_sweep.csv")
    bits = [int(r["gain_bits"]) for r in rows]
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
    ax[0].semilogy(bits, [float(r["predicted_naive_sym_resid"]) for r in rows],
                   "o--", label="predicted (error budget)")
    ax[0].semilogy(bits, [max(float(r["naive_max_sym_resid"]), 1e-18) for r in rows],
                   "s-", label="measured (compiled C)")
    ax[0].invert_xaxis()
    ax[0].set_xlabel("Kalman gain fractional bits")
    ax[0].set_ylabel(r"max $\|P-P^{\mathsf T}\|$")
    ax[0].set_title("Naive update: symmetry residual")
    ax[0].legend()

    ax[1].axhline(0.0, color="0.5", lw=0.8)
    ax[1].plot(bits, [float(r["naive_min_lambda"]) for r in rows], "s-", label="naive")
    ax[1].plot(bits, [float(r["joseph_min_lambda"]) for r in rows], "o-",
               label="Joseph")
    ax[1].invert_xaxis()
    ax[1].set_xlabel("Kalman gain fractional bits")
    ax[1].set_ylabel(r"min $\lambda_{\min}(P)$ over the run")
    ax[1].set_title("Positive definiteness")
    ax[1].legend()
    fig.tight_layout()
    fig.savefig(RESULTS / "predicted_vs_measured.png", dpi=140)
    plt.close(fig)


def plot_dt_study() -> None:
    rows = read("dt_study.csv")
    hz = [float(r["sample_rate_hz"]) for r in rows]
    fig, ax = plt.subplots(figsize=(7, 5))
    for key, label in (("float64_rms_vs_truth_deg", "float64"),
                       ("fixed_nominal_rms_vs_truth_deg", "fixed, per-quantity Q"),
                       ("fixed_global_rms_vs_truth_deg", "fixed, one global Q4.27"),
                       ("fixed_coarse_rms_vs_truth_deg", "fixed, Q1.24 covariance")):
        ax.loglog(hz, [float(r[key]) for r in rows], "o-", label=label)
    ax.set_xlabel("sample rate [Hz]")
    ax.set_ylabel("RMS angle error vs truth [deg]")
    ax.set_title("More samples stop helping once the format runs out")
    ax.legend()
    fig.tight_layout()
    fig.savefig(RESULTS / "dt_study.png", dpi=140)
    plt.close(fig)


def main() -> None:
    plot_divergence()
    plot_predicted_vs_measured()
    plot_dt_study()
    print(f"wrote {RESULTS}/divergence.png, predicted_vs_measured.png, dt_study.png")


if __name__ == "__main__":
    main()
